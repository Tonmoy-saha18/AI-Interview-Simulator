"""SQLAlchemy models for interview-related database tables."""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum as PyEnum

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Enum as SQLEnum,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import relationship

from ..core.database import Base


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class InterviewLinkStatus(PyEnum):
    """Status of an interview link."""

    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    EXPIRED = "expired"
    REVOKED = "revoked"


class InterviewType(PyEnum):
    """Type of interview."""

    BEHAVIORAL = "behavioral"
    TECHNICAL = "technical"
    MIXED = "mixed"
    CODING_ONLY = "coding_only"


class SessionStatus(PyEnum):
    """Status of an interview session."""

    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    ABANDONED = "abandoned"
    TIMED_OUT = "timed_out"


# ---------------------------------------------------------------------------
# Interview Links (HR-generated)
# ---------------------------------------------------------------------------

class InterviewLink(Base):
    """Model for interview links generated by HR."""

    __tablename__ = "interview_links"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    token = Column(String(255), unique=True, nullable=False, index=True)
    hr_email = Column(String(255), nullable=False)
    candidate_email = Column(String(255), nullable=False)
    candidate_name = Column(String(255), nullable=True)
    role = Column(String(255), nullable=False)
    level = Column(String(50), nullable=False, default="mid")
    question_limit = Column(Integer, nullable=False, default=3)
    expires_at = Column(DateTime, nullable=False)
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    used_at = Column(DateTime, nullable=True)
    status = Column(
        SQLEnum(
            InterviewLinkStatus,
            name="interview_link_status",
            values_callable=lambda x: [e.value for e in x],
        ),
        nullable=False,
        default=InterviewLinkStatus.PENDING,
    )
    organization_id = Column(
        UUID(as_uuid=True), ForeignKey("organizations.id", ondelete="SET NULL"), nullable=True, index=True
    )
    created_by_id = Column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True
    )
    interview_type = Column(String(50), nullable=True, default="behavioral")
    custom_instructions = Column(Text, nullable=True)
    notes = Column(Text, nullable=True)
    tags = Column(ARRAY(Text), nullable=True)
    session_id = Column(
        UUID(as_uuid=True), ForeignKey("interview_sessions.id", ondelete="SET NULL"), nullable=True
    )
    cv_file_path = Column(String(500), nullable=True)
    cv_extracted_data = Column(JSONB, nullable=True)

    organization = relationship("Organization", foreign_keys=[organization_id])
    created_by = relationship("User", foreign_keys=[created_by_id])
    results = relationship(
        "InterviewResult", back_populates="interview_link", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<InterviewLink(id={self.id}, token={self.token[:8]}..., status={self.status})>"

    def is_expired(self) -> bool:
        return datetime.utcnow() > self.expires_at

    def can_be_used(self) -> bool:
        return (
            self.status == InterviewLinkStatus.PENDING
            and not self.is_expired()
            and self.status != InterviewLinkStatus.REVOKED
        )


class InterviewResult(Base):
    """Model for storing completed interview results (legacy, used by HR flow)."""

    __tablename__ = "interview_results"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    interview_link_id = Column(
        UUID(as_uuid=True), ForeignKey("interview_links.id"), nullable=False
    )
    session_id = Column(String(255), nullable=False)
    final_feedback = Column(Text, nullable=True)
    overall_score = Column(String(50), nullable=True)
    qa_history = Column(JSONB, nullable=True)
    total_time_elapsed = Column(Integer, nullable=True)
    completed_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)

    interview_link = relationship("InterviewLink", back_populates="results")

    def __repr__(self) -> str:
        return (
            f"<InterviewResult(id={self.id}, interview_link_id={self.interview_link_id}, "
            f"session_id={self.session_id})>"
        )


# ---------------------------------------------------------------------------
# Interview Sessions (Sprint 3 — persistent sessions)
# ---------------------------------------------------------------------------

class InterviewSession(Base):
    """Persistent record of an interview session."""

    __tablename__ = "interview_sessions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=True, index=True
    )
    interview_link_id = Column(
        UUID(as_uuid=True), ForeignKey("interview_links.id"), nullable=True
    )
    role = Column(String(255), nullable=False)
    level = Column(String(50), nullable=False, default="mid")
    interview_type = Column(
        String(50), nullable=False, default=InterviewType.BEHAVIORAL.value
    )
    total_questions = Column(Integer, nullable=False, default=3)
    status = Column(
        String(50), nullable=False, default=SessionStatus.IN_PROGRESS.value
    )
    graph_state = Column(JSONB, nullable=True)
    started_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    completed_at = Column(DateTime, nullable=True)
    total_time_seconds = Column(Integer, nullable=True)

    user = relationship("User", backref="interview_sessions")
    interview_link = relationship("InterviewLink")
    questions = relationship(
        "InterviewQuestion",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="InterviewQuestion.sequence_number",
    )
    feedback = relationship(
        "InterviewFeedback",
        back_populates="session",
        uselist=False,
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<InterviewSession(id={self.id}, role={self.role}, status={self.status})>"


class InterviewQuestion(Base):
    """Individual question/answer within an interview session."""

    __tablename__ = "interview_questions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    session_id = Column(
        UUID(as_uuid=True),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    sequence_number = Column(Integer, nullable=False)
    parent_question_id = Column(
        UUID(as_uuid=True),
        ForeignKey("interview_questions.id"),
        nullable=True,
    )
    question_text = Column(Text, nullable=False)
    question_type = Column(String(50), nullable=True)
    difficulty = Column(String(50), nullable=True)
    answer_text = Column(Text, nullable=True)
    score = Column(Integer, nullable=True)
    evaluation_json = Column(JSONB, nullable=True)
    time_taken_seconds = Column(Integer, nullable=True)
    time_expired = Column(Boolean, nullable=False, default=False)

    session = relationship("InterviewSession", back_populates="questions")
    parent_question = relationship(
        "InterviewQuestion", remote_side=[id], backref="follow_ups"
    )

    def __repr__(self) -> str:
        return (
            f"<InterviewQuestion(id={self.id}, session_id={self.session_id}, "
            f"seq={self.sequence_number})>"
        )


class InterviewFeedback(Base):
    """Aggregated feedback for a completed interview session."""

    __tablename__ = "interview_feedback"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    session_id = Column(
        UUID(as_uuid=True),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
    )
    overall_score = Column(Integer, nullable=True)
    technical_depth_score = Column(Integer, nullable=True)
    communication_score = Column(Integer, nullable=True)
    problem_solving_score = Column(Integer, nullable=True)
    summary_text = Column(Text, nullable=True)
    strengths = Column(ARRAY(Text), nullable=True)
    improvements = Column(ARRAY(Text), nullable=True)
    per_question_analysis = Column(JSONB, nullable=True)

    session = relationship("InterviewSession", back_populates="feedback")

    def __repr__(self) -> str:
        return (
            f"<InterviewFeedback(id={self.id}, session_id={self.session_id}, "
            f"overall_score={self.overall_score})>"
        )
